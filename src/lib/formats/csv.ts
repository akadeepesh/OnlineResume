/**
 * Parse CSV (RFC 4180: quoted fields, "" escapes, commas and newlines inside
 * quotes, CRLF or LF) into rows of strings.
 */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  const input = text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;

  for (let i = 0; i < input.length; i++) {
    const char = input[i]!;
    if (quoted) {
      if (char === '"') {
        if (input[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += char;
      continue;
    }
    if (char === '"' && field === "") quoted = true;
    else if (char === ",") {
      row.push(field);
      field = "";
    } else if (char === "\n" || char === "\r") {
      if (char === "\r" && input[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += char;
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((cell) => cell.trim() !== ""));
}

/**
 * Rows as objects keyed by header. Header names are compared loosely
 * (case and spacing ignored), because exports rename columns over time.
 */
export function csvRecords(text: string): Record<string, string>[] {
  const [header, ...rows] = parseCsv(text);
  if (!header) return [];
  const keys = header.map(csvKey);
  return rows.map((row) => Object.fromEntries(keys.map((key, i) => [key, (row[i] ?? "").trim()])));
}

/** "Started On" → "startedon". Use it to look up columns from `csvRecords`. */
export const csvKey = (name: string) => name.toLowerCase().replace(/[^a-z0-9]/g, "");
